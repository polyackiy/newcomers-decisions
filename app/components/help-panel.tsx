"use client";
import { useEffect, useRef, useState } from "react";
import { X } from "lucide-react";
import type { AnalysisEnvelope, Dataset, Metrics } from "../../lib/contracts";
export type HelpTopic = "about" | "metrics" | "ai" | "storage";
const topics: [HelpTopic, string][] = [
  ["about", "Как пользоваться"],
  ["metrics", "Как считаем уходы"],
  ["ai", "Что делает AI"],
  ["storage", "Сохранение решений"],
];
export default function HelpPanel({
  topic,
  dataset,
  metrics,
  envelope,
  onClose,
  onReset,
}: {
  topic: HelpTopic;
  dataset: Dataset;
  metrics: Metrics;
  envelope: AnalysisEnvelope | null;
  onClose: () => void;
  onReset: () => void;
}) {
  const dialog = useRef<HTMLDialogElement>(null);
  const [current, setCurrent] = useState(topic);
  const [confirmReset, setConfirmReset] = useState(false);
  useEffect(() => {
    const opener = document.activeElement as HTMLElement;
    const d = dialog.current;
    const overflow = document.body.style.overflow;
    d?.showModal();
    document.body.style.overflow = "hidden";
    return () => {
      d?.close();
      document.body.style.overflow = overflow;
      opener?.focus();
    };
  }, []);
  return (
    <dialog
      ref={dialog}
      className="case-dialog help-dialog"
      aria-labelledby="help-title"
      onCancel={(e) => {
        e.preventDefault();
        onClose();
      }}
      onClick={(e) => {
        if (e.target === dialog.current) onClose();
      }}
    >
      <div className="dialog-inner">
        <header className="dialog-header">
          <h2 id="help-title">Справка</h2>
          <button className="text-button" onClick={onClose}>
            <X size={18} />
            Закрыть
          </button>
        </header>
        <div className="dialog-content">
          <nav className="help-nav" aria-label="Разделы справки">
            {topics.map(([id, label]) => (
              <button
                key={id}
                aria-pressed={current === id}
                className={current === id ? "active" : ""}
                onClick={() => setCurrent(id)}
              >
                {label}
              </button>
            ))}
          </nav>
          <div className="help-copy">
            {current === "about" && (
              <>
                <h3>Помочь новичку начать работать самостоятельно</h3>
                <p>
                  У руководителя склада и менеджера по персоналу разные части
                  одной истории: задача на приём, заявка на доступ, комментарий
                  наставника, запись об увольнении. Здесь связанные сведения
                  собраны по сотруднику, чтобы не искать их по отдельности.
                </p>
                <p>
                  Откройте ситуацию и проверьте исходные записи. Например,
                  незакрытая заявка сама по себе ещё не означает, что доступа
                  нет. Комментарий наставника помогает понять, как это
                  отражается на работе, а список вопросов — что нужно уточнить.
                </p>
                <h3>От разбора к проверяемому поручению</h3>
                <p>
                  В разделе «План и результат» можно отредактировать
                  предложение, указать ответственного и срок. Сохранённый текст
                  можно скопировать в рабочую задачу. После выполнения запишите,
                  что изменилось: например, смог ли сотрудник сам отобрать заказ
                  после выдачи доступа.
                </p>
                <h3>Что показывает этот пример</h3>
                <p>
                  Это прототип для ЗАО «ТГТ» на вымышленных данных. Имена,
                  должности, смены и ситуации придуманы для демонстрации
                  подхода; они не описывают реальных сотрудников или
                  подтверждённые процессы компании. Записи здесь вымышлены. Для
                  поручений предусмотрено создание задачи в Битрикс24 через
                  входящий вебхук; подключения к складской системе нет.
                </p>
              </>
            )}
            {current === "metrics" && (
              <>
                <h3>Ранний уход и окончание подработки — разные события</h3>
                <p>
                  Если человека наняли на ограниченный срок и он отработал его
                  до конца, это плановое завершение работы. В примере таких
                  сотрудников {metrics.confirmedPlanned}. Их не относим к ранним
                  уходам с постоянной работы.
                </p>
                <h3>Для сравнения нужен одинаковый срок наблюдения</h3>
                <p>
                  На дату обзора,{" "}
                  {new Intl.DateTimeFormat("ru-RU", {
                    dateStyle: "long",
                    timeZone: "UTC",
                  }).format(new Date(dataset.asOf + "T00:00:00Z"))}
                  , с выхода {metrics.maturePermanent} сотрудников на постоянную
                  работу прошло не менее 90 дней. Из них{" "}
                  {metrics.earlyPermanent} ушли до 90-го дня.{" "}
                  {metrics.earlyPermanentRate === null
                    ? "Данных для расчёта доли пока недостаточно."
                    : `Доля в этой группе — ${Math.round(metrics.earlyPermanentRate * 100)}%.`}
                </p>
                <p>
                  Ещё {metrics.recent} сотрудников вышли менее 90 дней назад.
                  Пока исключаем их и из числителя, и из знаменателя: иначе
                  новые приёмы искусственно улучшали бы показатель. Для их
                  текущей адаптации всё равно показываем ситуации, требующие
                  проверки.
                </p>
                <h3>Чего показатель не объясняет</h3>
                <p>
                  Количество уходов не устанавливает их причины и не оценивает
                  качество наставника. По каждому случаю нужны исходные записи и
                  разговор с участниками. Изменение этого показателя само по
                  себе также не доказывает пользу приложения.
                </p>
              </>
            )}
            {current === "ai" && (
              <>
                <h3>AI связывает сведения и предлагает следующий шаг</h3>
                <p>
                  Модель читает записи о приёме, адаптации и уходах. Она
                  выделяет ситуации, приводит цитаты, отмечает недостающую
                  информацию и предлагает, что проверить. Числа на главном
                  экране рассчитывает код по датам и виду занятости.
                </p>
                <p>
                  Приложение проверяет, что приведённая цитата действительно
                  есть в записи нужного сотрудника. Это проверка источника, а не
                  гарантия правильности вывода. Руководитель может прочитать
                  запись целиком, уточнить вывод и изменить предложенное
                  поручение. Уточнения сохраняются отдельно с отметкой
                  руководителя; первоначальный текст остаётся доступен.
                  Обновление AI не заменяет ваши правки.
                </p>
                <p>
                  AI не определяет, «подходит» ли человек компании, не
                  прогнозирует увольнение и не считает доказанную экономию.
                  Старый комментарий об отсутствии доступа нельзя автоматически
                  считать причиной последующего ухода.
                </p>
                <h3>Текущий разбор</h3>
                <p>
                  {envelope
                    ? `Модель: ${envelope.model}. Ответ получен ${new Intl.DateTimeFormat("ru-RU", { dateStyle: "medium", timeStyle: "short", timeZone: "Europe/Moscow" }).format(new Date(envelope.generatedAt))} по Москве. При первом открытии используется заранее полученный ответ для этих записей.`
                    : "Используется разбор, подготовленный вручную. Он не выдаётся за ответ модели."}
                </p>
                <p>
                  Кнопка «Обновить разбор» повторно отправляет эти же
                  вымышленные записи модели. Она не загружает новые сведения из
                  систем компании. При ошибке предыдущий разбор и ваши решения
                  остаются доступны.
                </p>
              </>
            )}
            {current === "storage" && (
              <>
                <h3>Поручение остаётся в вашем браузере</h3>
                <p>
                  Результат можно исправить или вернуть ситуацию в работу,
                  указав, что ещё нужно проверить. Предыдущая запись сохраняется
                  в истории изменений. В этом прототипе план и результат
                  сохраняются локально. Само сохранение не отправляет
                  уведомлений. После принятия плана можно отдельно создать
                  задачу в Битрикс24: для этого нужен настроенный
                  администратором входящий вебхук и числовой ID ответственного
                  на портале. Без подключения доступен только предварительный
                  просмотр, а поручение можно скопировать.
                </p>
                <p>
                  На другом устройстве или в другом браузере сохранённые решения
                  не появятся. Очистка данных сайта удалит их. Если браузер
                  запрещает сохранение, приложение предупредит об этом; тогда
                  изменения доступны только до закрытия страницы.
                </p>
                <h3>Как работает Битрикс24</h3>
                <p>
                  Перед созданием показываем текст, срок и получателя. Ссылка
                  появляется только после подтверждения API. Синхронизации
                  статусов нет: результат проверки руководитель фиксирует здесь
                  отдельно. Если ситуация возвращена в работу, откройте
                  существующую задачу и уточните её на портале.
                </p>
                <h3>Результат записывает руководитель</h3>
                <p>
                  Приложение сохраняет ваше описание результата, но не проверяет
                  выполнение операции на складе. Для проверки эффекта нужны
                  наблюдения: самостоятельная работа, повторные ошибки, время
                  наставника. В примере эти показатели не подменяются расчётной
                  экономией.
                </p>
                <div className="reset-box">
                  <p>
                    Можно удалить сохранённые в этом браузере планы, результаты
                    и уточнения выводов, чтобы пройти пример заново. Задачи, уже
                    созданные в Битрикс24, при этом не удаляются. Исходные
                    записи останутся.
                  </p>
                  {confirmReset ? (
                    <>
                      <button className="button secondary" onClick={onReset}>
                        Удалить планы и результаты
                      </button>
                      <button
                        className="text-button"
                        onClick={() => setConfirmReset(false)}
                      >
                        Отмена
                      </button>
                    </>
                  ) : (
                    <button
                      className="text-button"
                      onClick={() => setConfirmReset(true)}
                    >
                      Начать пример заново
                    </button>
                  )}
                </div>
              </>
            )}
          </div>
        </div>
      </div>
    </dialog>
  );
}
